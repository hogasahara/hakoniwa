# 平面図（案3）：北が上、道は南（下）。1m = 62px
from PIL import Image, ImageDraw, ImageFont
S=62; W,H=1100,1000
im=Image.new('RGB',(W,H),(246,243,236)); d=ImageDraw.Draw(im)
F=lambda n: ImageFont.truetype('/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf', n)
ox,oy=500,430   # 世界の (0,0)。x 右＝東、y 下＝南
P=lambda x,y:(ox+x*S, oy+y*S)
def rect(x0,y0,x1,y1,fill,out=(60,50,40),w=3): d.rectangle([P(min(x0,x1),min(y0,y1)),P(max(x0,x1),max(y0,y1))],fill=fill,outline=out,width=w)
def label(x,y,t,n=20,c=(40,34,28)):
    f=F(n); b=d.textbbox((0,0),t,font=f); d.text((P(x,y)[0]-(b[2]-b[0])/2,P(x,y)[1]-(b[3]-b[1])/2),t,font=f,fill=c)
f=F(28); t='雪野町立図書館　平面図（案3）　北が上'; b=d.textbbox((0,0),t,font=f); d.text(((W-b[2])/2,16),t,font=f,fill=(40,34,28))
# 本体（木造）：x -4..4.5、y -3（北）..3（南）
rect(-4.0,-3.0,4.5,3.0,(236,226,206))
# 閲覧室（東、南北に長い）
rect(1.2,-3.0,4.5,3.0,(232,214,180)); label(2.85,0.0,'閲覧室',28); label(2.85,0.6,'約12畳（3.3×6m）',15); label(2.85,1.0,'ストーブ・閲覧机',13)
rect(1.6,-2.75,4.1,-2.2,(200,170,120),w=1); label(2.85,-2.48,'新聞の閲覧台',12)
d.line([P(1.8,-3.0),P(3.9,-3.0)],fill=(150,190,220),width=8); label(2.85,-3.35,'北の窓',13)
for y in (-1.0,1.5): d.line([P(4.5,y-0.6),P(4.5,y+0.6)],fill=(150,190,220),width=8)
label(5.15,0.25,'東の窓',12)
# 書庫（コンクリート）：閲覧室の南の端から道の側へ張り出す
rect(1.2,3.0,4.5,6.4,(205,205,200)); label(2.85,4.6,'書庫（コンクリート造）',19); label(2.85,5.2,'床コンクリート・ひんやり',14)
d.line([P(1.7,3.0),P(2.9,3.0)],fill=(140,145,150),width=9); label(2.3,3.35,'鉄の引き戸',13,(70,70,75))
# 土間（細い通路）と上がり框
rect(-1.0,1.3,1.0,3.0,(190,185,175)); label(0,2.0,'土間',22); label(0,2.45,'幅2m・細い',13)
d.line([P(-1.0,1.3),P(1.0,1.3)],fill=(120,80,40),width=6); label(0,1.08,'上がり框',12,(120,80,40))
# 蔵書カードの棚（土間の右＝東、閲覧室の側から開ける）
rect(1.0,1.3,1.25,3.0,(120,85,50),w=1); label(1.95,1.75,'蔵書カードの棚',12,(90,60,30)); label(1.95,2.05,'（閲覧室側に扉）',11,(90,60,30))
# 広間と閲覧室への入口
label(0,0.45,'広間',18)
d.line([P(1.2,-0.4),P(1.2,1.3)],fill=(232,214,180),width=6)
# コの字のカウンター（正面＝東を閲覧室へ向け、南北に長い）
c=(150,110,70)
rect(0.6,-2.8,1.1,-0.6,c); rect(-0.6,-0.95,1.1,-0.6,c); rect(-0.6,-2.8,1.1,-2.45,c)
label(0.0,-1.7,'司書',14); label(-0.15,-0.28,'カウンター（コの字）',12,(110,70,40))
d.line([P(0.62,-1.7),P(1.6,-1.7)],fill=(180,60,40),width=2); label(2.15,-1.7,'正面→',12,(180,60,40))
# 西の棟：宿直室とトイレ
rect(-4.0,-3.0,-1.0,0.2,(226,220,200)); label(-2.5,-1.4,'宿直室',21); label(-2.5,-0.9,'（6畳）',13)
rect(-4.0,0.2,-1.0,3.0,(214,214,206)); label(-2.5,1.6,'トイレ・廊下',17)
d.line([P(-1.0,0.35),P(-1.0,1.05)],fill=(226,220,200),width=7); label(-0.7,0.7,'扉',12)
d.line([P(-1.0,-2.0),P(-1.0,-1.4)],fill=(226,220,200),width=7); label(-0.7,-1.7,'扉',11)
# 入口
d.line([P(-0.45,3.0),P(0.45,3.0)],fill=(246,243,236),width=8); label(-0.2,3.35,'入口（素朴な戸・上に蛍光灯）',13)
for (a,b) in [((0,4.2),(0,2.5)),((0,1.1),(0,-0.3))]: d.line([P(*a),P(*b)],fill=(180,60,40),width=3)
label(-0.6,3.9,'3歩',12,(180,60,40)); label(-0.6,0.35,'3歩',12,(180,60,40))
# 寸法・方位・道
d.line([P(-4,-3.7),P(4.5,-3.7)],fill=(90,90,90),width=1); label(0.25,-3.95,'8.5m',13,(90,90,90))
d.line([P(-4.6,-3),P(-4.6,3)],fill=(90,90,90),width=1); label(-5.0,0,'6m',13,(90,90,90))
label(-6.9,-4.4,'北 ↑',18); label(-6.9,6.4,'南 ↓',18); label(-7.4,1.6,'西',16); label(7.6,1.6,'東',16)
d.rectangle([0,P(0,7.6)[1],W,P(0,8.6)[1]],fill=(200,205,212)); label(0,8.1,'道（バス停・街灯）',16,(70,75,85))
im.save('plan-c.png'); print('ok')
