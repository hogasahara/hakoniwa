from PIL import Image, ImageDraw, ImageFont
S=66; W,H=1100,1120
im=Image.new('RGB',(W,H),(246,243,236)); d=ImageDraw.Draw(im)
F=lambda n: ImageFont.truetype('/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf', n)
ox,oy=520,560
P=lambda x,z:(ox+x*S, oy+z*S)
def rect(x0,z0,x1,z1,fill,out=(60,50,40),w=3): d.rectangle([P(min(x0,x1),min(z0,z1)),P(max(x0,x1),max(z0,z1))],fill=fill,outline=out,width=w)
def label(x,z,t,n=20,c=(40,34,28)):
    f=F(n); b=d.textbbox((0,0),t,font=f); d.text((P(x,z)[0]-(b[2]-b[0])/2,P(x,z)[1]-(b[3]-b[1])/2),t,font=f,fill=c)
f=F(28); t='雪野町立図書館　平面図（案2）'; b=d.textbbox((0,0),t,font=f); d.text(((W-b[2])/2,16),t,font=f,fill=(40,34,28))
