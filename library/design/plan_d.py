# 平面図（案4）：北が上、道は南（下）。1m = 64px
from PIL import Image, ImageDraw, ImageFont
S=64; W,H=1100,1000
im=Image.new('RGB',(W,H),(246,243,236)); d=ImageDraw.Draw(im)
F=lambda n: ImageFont.truetype('/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf', n)
ox,oy=470,400   # 世界の (0,0)。x 右＝東、y 下＝南
P=lambda x,y:(ox+x*S, oy+y*S)
def rect(x0,y0,x1,y1,fill,out=(60,50,40),w=3): d.rectangle([P(min(x0,x1),min(y0,y1)),P(max(x0,x1),max(y0,y1))],fill=fill,outline=out,width=w)
def label(x,y,t,n=20,c=(40,34,28)):
    f=F(n); b=d.textbbox((0,0),t,font=f); d.text((P(x,y)[0]-(b[2]-b[0])/2,P(x,y)[1]-(b[3]-b[1])/2),t,font=f,fill=c)
f=F(28); t='雪野町立図書館　平面図（案4）　北が上'; b=d.textbbox((0,0),t,font=f); d.text(((W-b[2])/2,16),t,font=f,fill=(40,34,28))
