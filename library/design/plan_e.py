label(5.15,0.25,'東の窓',12)
# 書庫：東の壁を一直線に。幅 2.2m
rect(2.3,3.0,4.5,6.4,(205,205,200)); label(3.4,4.6,'書庫',22); label(3.4,5.1,'コンクリート造',14); label(3.4,5.45,'床ひんやり',13)
d.line([P(2.8,3.0),P(4.0,3.0)],fill=(140,145,150),width=9); label(3.4,3.35,'鉄の引き戸',13,(70,70,75))
