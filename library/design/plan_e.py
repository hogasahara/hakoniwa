c=(150,110,70)
rect(0.55,-1.75,0.95,-0.65,c); rect(-0.45,-1.75,0.95,-1.45,c); rect(-0.45,-0.95,0.95,-0.65,c)
label(0.05,-1.2,'司書',13); label(0.0,-0.35,'カウンター',12,(110,70,40))
d.line([P(0.97,-1.2),P(1.55,-1.2)],fill=(180,60,40),width=2); label(1.95,-1.2,'正面→',12,(180,60,40))
label(0,-2.45,'事務の机・棚',13)
# 西の棟：北西の扉から西へ伸びる廊下、北側に部屋が並ぶ（x -8..-1）
rect(-8.0,-3.0,-1.0,0.6,(236,226,206))
