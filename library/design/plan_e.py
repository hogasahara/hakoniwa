rect(-1.0,1.3,1.0,3.0,(190,185,175)); label(0,2.0,'土間',22); label(0,2.45,'靴を脱ぐ',13)
d.line([P(-1.0,1.3),P(1.0,1.3)],fill=(120,80,40),width=6); label(0,1.08,'上がり框',12,(120,80,40))
rect(1.0,1.3,1.25,3.0,(120,85,50),w=1); label(1.9,1.75,'蔵書カードの棚',12,(90,60,30)); label(1.9,2.05,'（閲覧室側に扉）',11,(90,60,30))
